<script setup lang="ts">
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';
import { usePageNavigation } from '~/composables/usePageNavigation';

import UI_CONFIG from '~/config/ui';
import { SortDirection } from '~/types/common';
import { PoolSortField } from '~/types/pools';
import type { PoolModel } from '~/models/pools';
import { usePoolStore } from '~/stores/pools';
import { useAuthStore } from '~/stores/useAuthStore';

import DatatablePools from './datatable_pools.vue';
//-----> types
import type { JsonOptions, FilterItem } from '~/types/common';

import TheBreadcrumb from '~/components/layout/TheBreadcrumb.vue';
import SectionSearch from '~/components/common/TheSectionSearch.vue';
import FiltersButtons from '~/components/common/TheFilters.vue';

import TheSection from '~/components/common/TheSection.vue';
import SectionLoading from '~/components/common/TheSectionLoading.vue';
import TheSpacer from '~/components/common/TheSpacer.vue';

const menus = [
  { menu: '수영장', url: '/pools' },
];

const router = useRouter();

const authStore = useAuthStore();
const poolStore = usePoolStore();

// 상태 관리
const setFocus = ref(0);
const isLoading = ref(false);
const currentPage = ref(1);
const title = ref('');
const subtitle = ref('');
const rowsPerPage = 100; // ref(UI_CONFIG.rowsPerPage);

// ref로 사용할 때의 타입
const filters = ref<FilterItem[]>([
  // { field: 'competition', selected: '2024 고양 전국마스터즈 수영대회', options: ['2024 고양 전국마스터즈 수영대회'] },
  { field: 'course', selected: '전체', options: ['전체', 'LCM', 'SCM'] },
  { field: 'sido', selected: '전국', options: ['전국', '서울', '부산', '인천', '경기', '대구', '광주', '울산', '대전', '세종', '제주', '강원', '충남', '충북', '경남', '경북', '전남', '전북', '해외'] },
]);

///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {
  isLoading.value = true;
  try {
    isLoading.value = true;
    poolStore.filter = {
      name: '',
      course: '',
      sido: '',
      poolID: 0,
      sortField: 'dateStart',
      sortDirection: 'desc',
    };
    poolStore.pagination.rowsPerPage = rowsPerPage;

    subtitle.value = `${poolStore.filter.course} 수영장 목록 (${poolStore.filter.sido})`;
    poolStore.filter.sortField = PoolSortField.NAME;
    poolStore.filter.sortDirection = SortDirection.ASC;

    await poolStore.fetchPoolList(1, rowsPerPage);
    isLoading.value = false;
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
// history back시 onMount 처리
usePageNavigation(loadServerData);
///########################################################
///########################################################
const onFilterChange = async (field: string, value: string) => {
  poolStore.filter.name = '';
  isLoading.value = true;
  currentPage.value = 1;
  switch (field) {
    case "sido":
      poolStore.filter.sido = value;
      await poolStore.fetchPoolList(currentPage.value, rowsPerPage);
      break;
    case "course":
      poolStore.filter.course = value;
      await poolStore.fetchPoolList(currentPage.value, rowsPerPage);
      break;
    case "search":
      setFocus.value++;
      if (filters.value[0].field == 'search') {
        // 1. splice를 사용하여 0번째 요소 삭제
        filters.value.splice(0, 1);
      }
      poolStore.filter.name = '';
      return;
    default:
      return;
  }
  isLoading.value = false;
  subtitle.value = `${poolStore.filter.course} 수영장 목록 (${poolStore.filter.sido})`;
  if (poolStore.filter.name == '' && filters.value[0].field == 'search') {
    // 1. splice를 사용하여 0번째 요소 삭제
    filters.value.splice(0, 1);
  }
}
// 검색 필드 입력 값 바뀔 때
const onChangedField = async (value: string) => {
  if (value.length < 2) return;

  await onClickSearch(value)
};
// 검색 필드 click search
const onClickSearch = async (value: string) => {
  if (value.length < 2) return;

  poolStore.filter.name = value;
  poolStore.filter.course = '전체';
  poolStore.filter.sido = '전국';
  if (value.length > 0) title.value = `'${value}' 단어를 포함한 수영장`;
  subtitle.value = `${poolStore.filter.course} 수영장 목록 (${poolStore.filter.sido})`;

  isLoading.value = true;
  currentPage.value = 1;
  await poolStore.fetchPoolList(currentPage.value, rowsPerPage);
  isLoading.value = false; if (filters.value[0].field == 'search') {
    // 1. splice를 사용하여 0번째 요소 삭제
    filters.value.splice(0, 1);
  }
  if (value.length > 0) {
    // 1. splice를 사용하여 0번째 위치에 추가
    filters.value.splice(0, 0, { field: 'search', selected: value, options: [value] });
  }
};



// 부모 컴포넌트에 추가
const handlePageChange = async (page: number) => {
  currentPage.value = page;
  await poolStore.fetchPoolList(currentPage.value, rowsPerPage);
};
//======================================================================
// Button
//======================================================================
</script>

