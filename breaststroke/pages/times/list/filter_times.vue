// ref로 사용할 때의 타입
const filters = ref<FilterItem[]>([
  { field: 'gender', selected: '여자', options: ['남자', '여자'] },
  { field: 'style', selected: '평영', options: ['자유형', '배영', '평영', '접영', '개인혼영'] },
  { field: 'distance', selected: '50M', options: ['25M', '50M', '100M', '200M', '400M', '800M', '1500M'] },
]);

const props = defineProps({
  course: {
    type: String,
    default: ''
  },
  times: {
    type: Array as () => TimeModel[],
    default: () => [] as TimeModel[],
  },
  ageGroups: {
    type: Array as PropType<string[]>,
    default: () => [] as string[],
  },
});

const ageGroups = ref<string[]>([]);
const options = ref<JsonOptions>({
  gender: 'women',
  style: 'breaststroke',
  distance: '50M',
});

// modelValue 변경 감지
watch(() => props.times, (newTimes) => {
  const originalTimeList = JSON.parse(JSON.stringify(newTimes)) as TimeModel[];
  
  // ageGroup 체크
  filters.value = filters.value.slice(0, 3);
  if (props.ageGroups.length === 0) return;

  const ageGroup: FilterItem  = { field: 'ageGroup', selected: props.ageGroups[0], options: props.ageGroups };
  filters.value.push(ageGroup);


}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가

// filter가 변경될 때 parent로 filter 데이터를 업데이트하는 함수
const emit = defineEmits(['change-discipline']);

// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  try {
    switch (field) {
    case 'style':
      options.value.style = getStyleEngByKor(value);
      break;
    case 'gender':
    options.value.gender = getGenderByKor(value);
      break;
    default:
    options.value[field] = value;
      break;
    }    
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  } finally {
    emit('change-discipline', options.value);
  }
}
