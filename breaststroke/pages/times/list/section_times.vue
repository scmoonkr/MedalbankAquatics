import SectionLoading from '~/components/common/TheSectionLoading.vue';
// import FilterTimes from '~/components/common/TheFiltersTimes.vue';
import FilterTimes from './filter_times.vue';

const timeStore = useTimeStore();

///########################################################
/// parent로부터 전달 받을 값 정의
///########################################################
const props = defineProps({
  competition: {
    type: Object,
    default: () => ({}),
  }
});

// 상태 관리
const viewTimesSection = ref(false);
const timeList = ref<TimeModel[]>([]);
const isLoading = ref(false);
const currentPage = ref(1);
const timeTitle = ref("");
const ageGroups = ref<string[]>([]);

const emit = defineEmits([
  'close-times-section',
]);
// 부모 컴포넌트에 추가
const closeTimesSection = async () => {
  // viewTimesSection.value = false;
  emit('close-times-section');
};

///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
watch(() => props.competition.competitionID, async (competition) => {
  if (!competition || !competition.competitionID) return;
  
  try {
    // 데이터 로딩 로직...
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  }
}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가

///########################################################
///########################################################



//======================================================================
// Button
//======================================================================

//--------------------------------------------
// 필터 변경 처리
//--------------------------------------------
const onNewFilterChange = async (newFilters: any) => {
  isLoading.value = true;
  timeStore.filter.discipline = newFilters.discipline === 'all' ? undefined : newFilters.discipline;
  timeStore.filter.gender = newFilters.gender === 'all' ? undefined : newFilters.gender;
  timeStore.filter.course = newFilters.course === 'all' ? undefined : newFilters.course;
  timeStore.filter.distance = newFilters.distance === 'all' ? undefined : newFilters.distance;

  filterTimes();
}

function filterTimes() {
  const originalTimeList = JSON.parse(JSON.stringify(timeStore.timeList)) as TimeModel[];
  timeList.value = originalTimeList.filter(time => time.discipline === timeStore.filter.discipline &&
                                                    time.gender === timeStore.filter.gender &&                               
                                                    time.distance === timeStore.filter.distance
                                                  )

  ageGroups.value = [...new Set(timeList.value.map(el => el.ageGroup))];

  if (ageGroups.value.length > 0) {
    timeList.value = timeList.value.filter(time => time.ageGroup === ageGroups.value[0]);
  }
  timeTitle.value = timeStore.filter.ageGroup + " " + makeTimesTitle(timeStore.filter);
}
