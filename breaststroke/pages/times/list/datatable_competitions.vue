<script setup lang="ts">
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';

import UI_CONFIG from '~/config/ui';
import { SortDirection } from '~/types/common';
import { CompetitionSortField } from '~/types/competitions';
import type { CompetitionModel } from '~/models/competitions';
import { useCompetitionStore } from '~/stores/competitions';

import DataTable from '~/components/common/DataTable.vue';
import TheTooltipDialog from '~/components/common/TheTooltipDialog.vue';
const showTooltip = ref(false);

const router = useRouter();
const competitionStore = useCompetitionStore();

// 상태 관리
const isLoading = ref(false);
const selectedItems = ref<number[]>([]);
const timeToDelete = ref<number | null>(null);
const showDeleteModal = ref(false);

const props = defineProps({
  competitions: {
    type: Array as () => CompetitionModel[],
    default: () => [] as CompetitionModel[],
  },
  totalPages: {
    type: Number,
    default: 1,
  },
  page: {
    type: Number,
    default: 1,
  },
});

const currentPage = computed(() => props.page);

//===================================
// computed: 상태변화
//===================================
const tableData = computed(() => {
  // return competitionStore.filteredTimeList;
  return props.competitions.map((data: CompetitionModel) => {
    // checked 속성 추가
    return {
      ...data,
      checked: selectedItems.value.includes(data.competitionID)
    };
  });
});

///########################################################
///####################DataTable###########################
///########################################################
// DataTable 설정
const columns = [
  { key: 'dateStart', label: '일자', sortable: false },
  { key: 'fullname', label: '대회', sortable: false },
  { key: 'athleteCount', label: '참가인원', sortable: false, align: 'right' },
];

const showDeleteButton = computed(() => selectedItems.value.length > 0);

// Table header sort changed
const sortColumnChanged = async (column: string) => {
  competitionStore.filter.sortField = column as CompetitionSortField;
  competitionStore.filter.sortDirection = competitionStore.filter.sortDirection === SortDirection.ASC ? SortDirection.DESC : SortDirection.ASC;
  await competitionStore.fetchCompetitionList(1, competitionStore.pagination.limit);
};

const toggleSelectAll = (checked: boolean) => {
  if (checked) {
    selectedItems.value = tableData.value.map(item => item.competitionID);
  } else {
    selectedItems.value = [];
  }
};
const clickTableCell = async (item: CompetitionModel, column: string) => {
  // router.push(`/competition/${item.competitionID}`);
  if (item.athleteCount) {
    emit('click-cell', item.competitionID);
  } else {
    showTooltip.value = true;
  }
};

// 페이지 변경 처리
const pageChanged = async (page: number) => {
  emit('page-change', page);
};

const emit = defineEmits([
  'page-change', 'click-cell',
]);

const toggleSelectItem = (id: number, checked: boolean) => {
  if (checked) {
    if (!selectedItems.value.includes(id)) {
      selectedItems.value.push(id);
    }
  } else {
    selectedItems.value = selectedItems.value.filter(itemId => itemId !== id);
  }
};

const confirmDelete = (id: number) => {
  timeToDelete.value = id;
  showDeleteModal.value = true;
};

const confirmDeleteAction = async () => {
  // if (timeToDelete.value) {
  //   // 단일 항목 삭제
  //   await competitionStore.deleteTime(timeToDelete.value);
  // } else if (selectedItems.value.length > 0) {
  //   // 여러 항목 삭제
  //   await competitionStore.bulkDeleteTimes(selectedItems.value);
  //   selectedItems.value = [];
  // }

  // showDeleteModal.value = false;
  // timeToDelete.value = null;
};

const editRecord = (id: number) => {
  router.push(`/times/${id}/edit`);
};

const viewRecordDetails = (id: number) => {
  router.push(`/times/${id}`);
};
///########################################################
///########################################################

// 이미지 로드 실패 처리
const handleImageError = (event: Event): void => {
  (event.target as HTMLImageElement).src = '/images/not_found.jpg';
};

</script>

