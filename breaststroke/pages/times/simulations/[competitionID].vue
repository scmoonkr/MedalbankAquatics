<script setup lang="ts">
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';
import { usePageNavigation } from '~/composables/usePageNavigation';

import UI_CONFIG from '~/config/ui';
//-----> types
import type { JsonOptions, FilterItem } from '~/types/common';
import type { TimeModel } from '~/models/times';
import type { CompetitionModel } from '~/models/competitions';
import { useSimulationStore } from '~/stores/simulation';

import DataTableTimes from './datatable_times.vue';
import TheSection from '~/components/common/TheSection.vue';
import SectionLoading from '~/components/common/TheSectionLoading.vue';
import FiltersTimes from '~/components/common/TheFiltersTimes.vue';
import TheTooltipRun from '~/components/common/TheTooltipRun.vue';
const showTooltip = ref(false);

const router = useRouter();
const route = useRoute();

const simulationStore = useSimulationStore();

///########################################################
/// parent로부터 전달 받을 값 정의
///########################################################
const isLoading = ref(false);
const competitionID = ref(0);
const timeList = ref<TimeModel[]>([]);
const course = ref("LCM");
const competitionName = ref("");
const timeTitle = ref("");
const rowsPerPage = 100;

const ageGroups = ref<string[]>([]);
const options = ref<JsonOptions>({
  gender: 'women',
  discipline: 'BR',
  distance: '50M',
});

const filters = ref<FilterItem[]>([
  { field: 'competition', selected: '2024 고양 전국마스터즈 수영대회', options: ['2024 고양 전국마스터즈 수영대회'] },
  { field: 'gender', selected: '여자', options: ['남자', '여자'] },
  { field: 'discipline', selected: '평영', options: ['자유형', '배영', '평영', '접영', '개인혼영'] },
  { field: 'distance', selected: '50M', options: ['25M', '50M', '100M', '200M', '400M', '800M', '1500M'] },
  { field: 'ageGroup', selected: '전체그룹', options: ['전체그룹'] },
]);

///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {

  try {
    isLoading.value = true;
    await nextTick();

    const competitionIDStr = route.params.competitionID;
    options.value = {
      gender: "여자",
      discipline: "평영",
      distance: "50M",
      ageGroup: "전체그룹"
    };

    await simulationStore.fetchSimulationCompetitions();
    if (simulationStore.competitionList.length > 0) {
      filters.value[0].selected = simulationStore.competitionList[0].fullname;
      competitionName.value = simulationStore.competitionList[0].fullname;
      filters.value[0].options = simulationStore.competitionList.map(el => el.fullname);
      if (simulationStore.competitionList.length == 1) {
        await simulationStore.fetchSimulationById(simulationStore.competitionList[0].competitionID);
      }
      filterTimes();
    }

    isLoading.value = false;
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// history back시 onMount 처리
usePageNavigation(loadServerData);

///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################

///########################################################
///########################################################
// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  if (simulationStore.competitionList.length == 0 && field != "competition") return;

  try {
    switch (field) {
      case 'discipline':
        options.value.discipline = value;
        break;
      case 'gender':
        options.value.gender = value;
        break;
      case 'competition':
        const competition = simulationStore.competitionList.find(competition => competition.fullname == value);
        if (competition) {
          await simulationStore.fetchSimulationById(competition.competitionID);
          competitionName.value = competition.fullname;
        }

        // router.push(`/times/competitions`);
        return;
      default:
        options.value[field] = value;
        break;
    }
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  } finally {
    filterTimes();
  }
}
const confirmDialog = (value: boolean) => {
  showTooltip.value = false;
  if (value) {
    router.push(`/times/competitions`);
  }
}


//======================================================================
// Button
//======================================================================

//--------------------------------------------
// 필터 변경 처리
//--------------------------------------------
function filterTimes() {
  const discipline = getStyleEngByKor(options.value.discipline);
  const gender = getGenderByKor(options.value.gender);
  const originalTimeList = JSON.parse(JSON.stringify(simulationStore.currentSimulation)) as TimeModel[];
  timeList.value = originalTimeList.filter(time => time.discipline === discipline &&
    time.gender === gender &&
    time.distance === options.value.distance
  )

  ageGroups.value = ["전체그룹", ...new Set(timeList.value.map(el => el.ageGroup))];

  if (!options.value.ageGroup) options.value.ageGroup = ageGroups.value[0];
  if (options.value.ageGroup != "전체그룹") {
    timeList.value = timeList.value.filter(time => time.ageGroup === options.value.ageGroup);
  }
  timeList.value = sortAndRankTimes(timeList.value);


  // ageGroup 체크
  filters.value = filters.value.slice(0, 4);

  const ageGroup: FilterItem = { field: 'ageGroup', selected: options.value.ageGroup, options: ageGroups.value };
  filters.value.push(ageGroup);
  timeTitle.value = makeTimesTitle(options.value);

}
</script>

