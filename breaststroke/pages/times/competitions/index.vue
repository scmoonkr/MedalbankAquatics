<script setup lang="ts">
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';
const router = useRouter();

import { usePageNavigation } from '~/composables/usePageNavigation';

import UI_CONFIG from '~/config/ui';
import { useCompetitionStore } from '~/stores/competitions';
import { useTimeStore } from '~/stores/times';
//-----> types
import type { JsonOptions, FilterItem } from '~/types/common';

import DatatableCompetitions from './datatable_competitions.vue';

import TheSection from '~/components/common/TheSection.vue';
import SectionLoading from '~/components/common/TheSectionLoading.vue';
import FilterButtons from '~/components/common/TheFilters.vue';
import { CompetitionModel } from '~/models/competitions';

const competitionStore = useCompetitionStore();

// 상태 관리
const isLoading = ref(false);
const currentPage = ref(1);
const indexMasters = ref(0);
const indexYear = ref(1);
const rowsPerPage = ref(1000); // UI_CONFIG.rowsPerPage);
const competitionList = ref<CompetitionModel[]>([]);

// ref로 사용할 때의 타입
const filters = ref<FilterItem[]>([
  // { field: 'competition', selected: '2024 고양 전국마스터즈 수영대회', options: ['2024 고양 전국마스터즈 수영대회'] },
  { field: 'masters', selected: '비등록', options: ['등록', '비등록'] },
  { field: 'year', selected: '', options: [] },
  { field: 'times', selected: '기록지있는대회만보기', options: ['전체대회보기', '기록지있는대회만보기'] },
]);
///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {

  // years계산
  const noOfYear = 9;
  const currentYear = new Date().getFullYear();
  indexYear.value = filters.value.findIndex(el => el.field === 'year');
  for (let year = currentYear; year >= currentYear - (noOfYear - 1); year--) {
    filters.value[indexYear.value].options.push(year.toString());
  }
  filters.value[indexYear.value].selected = filters.value[indexYear.value].options[0];


  indexMasters.value = filters.value.findIndex(el => el.field === 'masters');

  isLoading.value = true;
  try {
    isLoading.value = true;
    competitionStore.filter = {
      year: filters.value[indexYear.value].selected,
      // masters: 'masters',
      masters: filters.value[indexMasters.value].selected,
      sortField: 'dateStart',
      sortDirection: 'desc',
    };

    // competitionStore.filter.sortField = CompetitionSortField.DATESTART;
    // competitionStore.filter.sortDirection = SortDirection.DESC;

    currentPage.value = 1;
    await competitionStore.fetchCompetitionList(currentPage.value, rowsPerPage.value);
    competitionList.value = competitionStore.competitionList.filter(competition => competition.athleteCount > 0);
    isLoading.value = false;
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// history back시 onMount 처리
usePageNavigation(loadServerData);
///########################################################
///########################################################

///########################################################
/// parent로 competition 정보 넘기기
///########################################################
const onFilterChange = async (field: string, value: string) => {
  isLoading.value = true;
  currentPage.value = 1;
  switch (field) {
    case "masters":
      competitionStore.filter.masters = value;
      await competitionStore.fetchCompetitionList(currentPage.value, rowsPerPage.value);
      competitionList.value = competitionStore.competitionList.filter(competition => competition.athleteCount > 0);
      break;
    case "year":
      competitionStore.filter.year = value;
      await competitionStore.fetchCompetitionList(currentPage.value, rowsPerPage.value);
      competitionList.value = competitionStore.competitionList.filter(competition => competition.athleteCount > 0);
      break;
    case "times":
      if (value === '전체대회보기') {
        competitionList.value = competitionStore.competitionList.filter(competition => true);
      } else {
        competitionList.value = competitionStore.competitionList.filter(competition => competition.athleteCount > 0);
      }
      break;
    default:
      return;
  }
  isLoading.value = false;
}
// const emit = defineEmits([
//   'selected-competition',
// ]);
// click competition row
const handleClickCell = async (competitionID: number) => {
  // emit('selected-competition', competition);
  router.push(`/times/results/${competitionID}`);
};

///########################################################
/// onChange event
///########################################################
const handlePageChange = async (page: number) => {
  currentPage.value = page;
  await competitionStore.fetchCompetitionList(currentPage.value, rowsPerPage.value);
};
const pageTitle = computed(() => {
  return `결과를 조회할 대회를 선택해주세요.`;
});
const pageSubtitle = computed(() => {
  return `${filters.value[indexYear.value].selected}년도 ${filters.value[indexMasters.value].selected} 대회 목록`;
});
</script>

