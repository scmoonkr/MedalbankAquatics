async function loadServerData() {
  isLoading.value = true;
  try {
    isLoading.value = true;

    // 초기 필터 설정
    leaderboardStore.filter.ageGroup = '';
    leaderboardStore.filter.sido = '';
    // leaderboardStore.filter.masters = 'masters';
    // leaderboardStore.filter.gender = 'women';
