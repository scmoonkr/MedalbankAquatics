<script setup lang="ts">
const router = useRouter();
import { TimeModel } from '~/models/times';

import DataTable from '~/components/common/DataTable.vue';

const props = defineProps({
  time: {
    type: TimeModel,
    default: {} as TimeModel,
  },
});

interface BestTimeInfo {
  bestTime?: string;
  bestTimeStamp?: number;
  bestTimeDiff?: number;
  bestTimeDiffs?: string;
  avgTime?: string;
  avgTimeStamp?: number;
  avgTimeDiff?: number;
  avgTimeDiffs?: string;
  seasonBestTime?: string;
  seasonBestTimeStamp?: number;
  seasonBestTimeDiff?: number;
  seasonBestTimeDiffs?: string;
  seasonAvgTime?: string;
  seasonAvgTimeStamp?: number;
  seasonAvgTimeDiff?: number;
  seasonAvgTimeDiffs?: string;
}
// 테이블 데이터 계산 속성 - 안전하게 처리
const tableData = computed(() => {
  if (!props.time) return [];
  const style = getStyleKorByEng(props.time.style);
  columns[0].label = `${style} ${props.time.distance}`;

  const timeStamp = convertStringToTimeStamp(props.time.time);

  const best: BestTimeInfo = props.time.extraInfo || {};
  if (best.bestTime) {
    best.bestTimeStamp = convertStringToTimeStamp(best.bestTime);
    best.bestTimeDiff = best.bestTimeStamp - timeStamp;
    best.bestTimeDiffs = convertTimeStampToString(best.bestTimeDiff);
  }
  if (best.avgTime) {
    best.avgTimeStamp = convertStringToTimeStamp(best.avgTime);
    best.avgTimeDiff = best.avgTimeStamp - timeStamp;
    best.avgTimeDiffs = convertTimeStampToString(best.avgTimeDiff);
  }
  if (best.seasonBestTime) {
    best.seasonBestTimeStamp = convertStringToTimeStamp(best.seasonBestTime);
    best.seasonBestTimeDiff = best.seasonBestTimeStamp - timeStamp;
    best.seasonBestTimeDiffs = convertTimeStampToString(best.seasonBestTimeDiff);
  }
  if (best.seasonAvgTime) {
    best.seasonAvgTimeStamp = convertStringToTimeStamp(best.seasonAvgTime);
    best.seasonAvgTimeDiff = best.seasonAvgTimeStamp - timeStamp;
    best.seasonAvgTimeDiffs = convertTimeStampToString(best.seasonAvgTimeDiff);
  }

  const arr = [];
  arr.push({
    style: '개인최고기록',
    time: (best as any).bestTime || "",
    diff: best.bestTimeDiffs,
    stroke: '준비중',
    breath: '준비중',
    kick: '준비중'
  });
  arr.push({
    style: '개인기록평균',
    time: (best as any).avgTime || "",
    diff: best.avgTimeDiffs,
    stroke: '준비중',
    breath: '준비중',
    kick: '준비중'
  });
  arr.push({
    style: '개인시즌최고',
    time: (best as any).seasonBestTime || "",
    diff: best.seasonBestTimeDiffs,
    stroke: '준비중',
    breath: '준비중',
    kick: '준비중'
  });
  arr.push({
    style: '개인시즌평균',
    time: (best as any).seasonAvgTime || "",
    diff: best.seasonAvgTimeDiffs,
    stroke: '준비중',
    breath: '준비중',
    kick: '준비중'
  });
  arr.push({
    style: '결과',
    time: convertTimeStampToString(timeStamp),
    diff: best.seasonAvgTimeDiffs,
    stroke: '준비중',
    breath: '준비중',
    kick: '준비중'
  });
  return arr;
});
const columns = [
  { key: 'style', label: '종목', sortable: false },
  { key: 'time', label: '결과', sortable: false },
  { key: 'diff', label: '차이', sortable: false },
  { key: 'stroke', label: '스트로크', sortable: false },
  { key: 'breath', label: '호흡', sortable: false },
  { key: 'kick', label: '돌핀킥', sortable: false },
];

// 테이블 셀 클릭 처리
const clickTableCell = (item: {}, column: string) => {

  if ((item as any).timeID) {
    router.push(`/time/${(item as any).timeID}`);
  }
};
</script>

