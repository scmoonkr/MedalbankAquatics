<script setup lang="ts">
const router = useRouter();
import { TimeModel } from '~/models/times';

import DataTable from '~/components/common/DataTable.vue';

const props = defineProps({
  time: {
    type: TimeModel,
    default: {} as TimeModel,
  },
});


// 테이블 데이터 계산 속성 - 안전하게 처리
const tableData = computed(() => {
  const arr = [];

  let meterPerSec = "";
  if (props.time && props.time.time) {
    const timeStamp = timeStringToSeconds(props.time.time);
    const ms = parseInt(props.time.distance.replace("M", "")) / timeStamp;
    meterPerSec = ms.toFixed(2).toString();
  }

  arr.push({
    style: '속도(M/s)',
    all: `${meterPerSec}M/s(초속${meterPerSec}M)`,
    first: '준비중',
    last: '준비중',
    distance15: '준비중',
    distance25: '준비중',
    distance35: '준비중',
    distance45: '준비중',
    distance50: '준비중'
  });
  arr.push({
    style: '스트로크레이트(m/s)',
    all: '미입력',
    first: '준비중',
    last: '준비중',
    distance15: '준비중',
    distance25: '준비중',
    distance35: '준비중',
    distance45: '준비중',
    distance50: '준비중'
  });
  arr.push({
    style: 'DPS(미터)',
    all: '미입력',
    first: '준비중',
    last: '준비중',
    distance15: '준비중',
    distance25: '준비중',
    distance35: '준비중',
    distance45: '준비중',
    distance50: '준비중'
  });
  return arr;
});
const columns = [
  { key: 'style', label: '스플릿', sortable: false },
  { key: 'all', label: '전체구간(0-50M)', sortable: false },
  { key: 'first', label: '전반(0-25M)', sortable: false },
  { key: 'last', label: '후반(25-50M)', sortable: false },
  { key: 'distance15', label: '0-15M', sortable: false },
  { key: 'distance25', label: '15-25M', sortable: false },
  { key: 'distance35', label: '25-35M', sortable: false },
  { key: 'distance45', label: '35-45M', sortable: false },
  { key: 'distance50', label: '45-50M', sortable: false },
];

// 테이블 셀 클릭 처리
const clickTableCell = (item: {}, column: string) => {

  if ((item as any).timeID) {
    router.push(`/time/${(item as any).timeID}`);
  }
};
</script>

