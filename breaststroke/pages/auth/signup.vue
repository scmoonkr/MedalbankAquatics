            <h1>개인정보의 수집</h1>
            <p>
              ① 회사는 회원가입 시 또는 서비스를 이용하는 과정에서 서비스 제공을 위해 필요한 최소한의 개인정보를 수집합니다. 서비스 제공을 위해 반드시 필요한 최소한의 정보를 필수항목으로, 그 외 특화된 서비스를 제공하기 위해 추가 수집하는 정보는 선택항목으로 동의를 받고 있으며, 선택항목에 동의하지 않은 경우에도 서비스 이용에 제한은 없습니다.<br />
              ② 회원가입 시점에 회사가 이용자로부터 수집하는 개인정보는 아래와 같습니다.<br />
              1. 회원 가입 시 필수항목으로 아이디(이메일 주소), 비밀번호, 이름, 생년월일, 성별, 휴대전화번호를, 선택항목으로 별명을 수집합니다. 실명 인증된 아이디로 가입 시, 암호화된 동일인 식별정보(CI), 중복가입 확인정보(DI), 내/외국인 정보를 함께 수집합니다. 만14세 미만 아동의 경우, 법정대리인 정보(법정대리인의 이름, 생년월일, 성별, 중복가입확인정보(DI), 휴대전화번호)를 추가로 수집합니다.<br />
              2. 사업자/단체 회원 가입 시 필수 항목으로 아이디(이메일 주소), 비밀번호, 사업자/단체명, 담당자 본인 인증정보(이름, 생년월일, 성별, 아이디, 암호화된 이용자 확인값(CI), 중복가입확인정보(DI), 내/외국인 여부), 담당자 연락처(이메일 주소, 휴대전화번호), 선택항목으로 사업자/단체 대표자명을 수집합니다.<br />
              ③ 서비스 이용 과정에서 회사가 이용자로부터 수집하는 개인정보는 아래와 같습니다.<br />
              1. 이용자는 회원정보 또는 개별 서비스에서 프로필 정보(별명, 프로필 사진)를 설정할 수 있습니다. 회원정보에 별명을 입력하지 않은 경우에는 실명이 별명으로 자동 입력됩니다.<br />
              2. 회사 내의 개별 서비스 이용, 이벤트 응모 및 경품 신청 과정에서 해당 서비스의 이용자에 한해 추가 개인정보 수집이 발생할 수 있습니다. 추가로 개인정보를 수집할 경우에는 해당 개인정보 수집 시점에서 이용자에게 ‘수집하는 개인정보 항목, 개인정보의 수집 및 이용목적, 개인정보의 보관기간’에 대해 안내 드리고 동의를 받습니다.<br />
              3. 서비스 이용 과정에서 이용자가 입력한 정보를 저장(수집)하거나, 이용자에 관한 정보(IP 주소, 쿠키, 서비스 이용 기록, 기기정보, 위치정보)를 자동화된 방법으로 생성하여 저장(수집)하거나, 이용자 기기의 고유한 정보를 원래의 값을 확인하지 못 하도록 안전하게 변환하여 수집합니다. 또한 이미지 및 음성을 이용한 검색 서비스 등에서 이미지나 음성이 수집될 수 있습니다.<br />
