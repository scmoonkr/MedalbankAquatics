<script setup lang="ts">
import { ref, computed } from 'vue';
import { useRouter } from 'vue-router';
import type { Top3Category } from '~/types/main';
import type { LeaderboardModel } from '~/models/leaderboard';

import CellText from '~/components/common/cells/CellText.vue'
import CellNumber from '~/components/common/cells/CellNumber.vue'
import CellTextText from '~/components/common/cells/CellTextText.vue'
import CellDiscipline from '~/components/common/cells/CellDiscipline.vue'
import CellNumberText from '~/components/common/cells/CellNumberText.vue'
import CellTimeDate from '~/components/common/cells/CellTimeDate.vue'
import CellTimeAthlete from '~/components/common/cells/CellTimeAthlete.vue'
import CellAthleteText from '~/components/common/cells/CellAthleteText.vue'
import CellCompetitionText from '~/components/common/cells/CellCompetitionText.vue'

import DataTable from '~/components/common/DataTable.vue';

const router = useRouter();
const isLoading = ref(false);

const props = defineProps({
  top3: {
    type: Array as () => Top3Category[],
    default: () => [],
    required: true,
  },
});

const columns = [
  { key: 'style', label: '종목', sortable: false },
  { key: 'rank1', label: '금', sortable: false },
  { key: 'rank2', label: '은', sortable: false },
  { key: 'rank3', label: '동', sortable: false },
];

const top3Record = computed(() => {
  const top3Arr = [];
  for (const data of props.top3) {
    const top3 = {
      gender: data.gender,
      style: data.style,
      course: data.course,
      distance: data.distance,
      rank1: { name: '', time: '', thumbnail: '' },
      rank2: { name: '', time: '', thumbnail: '' },
      rank3: { name: '', time: '', thumbnail: '' },
    };
    for (let no = 0; no < data.times.length && no < 3; no++) {
      (top3 as any)[`rank${no + 1}`] = data.times[no];
    }
    top3Arr.push(top3);
  }
  return top3Arr;
});

const handleImageError = (event: Event): void => {
  (event.target as HTMLImageElement).src = '/images/not_found.jpg';
};

const clickTableCell = (item: {}, column: string) => {
  switch (column) {
    case "style": // leaderboard gender, style, distance, course
    router.push(`/leaderboards?style=${(item as any).style}&gender=${(item as any).gender}&course=${(item as any).course}&distance=${(item as any).distance}`)
    // router.push(`/leaderboards/view/${(item as any).timeID}`)
      break;
    default:
      if ((item as any)[column].athleteID) {
        router.push(`/athlete/${(item as any)[column].athleteID}`)
      }
      break;
  }
};
</script>

