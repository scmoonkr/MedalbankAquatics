<script setup>
import { ref } from 'vue';

import TheSpacer from '~/components/common/TheSpacer.vue';
import TheTooltipDialog from '~/components/common/TheTooltipDialog.vue';

import { useRouter } from 'vue-router'
const router = useRouter()

const showTooltip = ref(false);
const searchQuery = ref('');

const props = defineProps({
  name: {
    type: String,
    default: '',
  },
});

const clickMyTimeResult = () => {
  if (props.athleteID === 0) {
    showTooltip.value = true;
  } else {
    router.push(`/search/?name=${props.name}`)
  }
}
const handleSearch = () => {
  if (!searchQuery.value.trim()) return;
  // 검색 로직 구현
  router.push(`/search?name=${searchQuery.value}`);
};
</script>


