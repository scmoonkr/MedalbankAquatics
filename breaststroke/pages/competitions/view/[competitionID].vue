async function loadServerData() {

  try {
    isLoading.value = true;
    await nextTick();

    const competitionIdStr = route.params.competitionID;
    const competitionId = parseInt(competitionIdStr as string, 10);

    // 비동기 작업 완료 후 상태 확인
    await competitionStore.fetchCompetitionById(competitionId);
console.log("competitionStore.currentCompetition=", competitionStore.currentCompetition);
  } catch (error) {
    console.error("Error in onMounted:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
usePageNavigation(loadServerData);

// 날짜 양식 변경
function formatKoreanDateWithDay(dateString: string): string {
  if (!dateString) return '';
  const date = new Date(dateString);
  const days = ['일요일', '월요일', '화요일', '수요일', '목요일', '금요일', '토요일'];
  const dayName = days[date.getDay()];
  const year = date.getFullYear();
  const month = date.getMonth() + 1;
  const day = date.getDate();
  return `${year}년 ${month}월 ${day}일 ${dayName}`;
}
