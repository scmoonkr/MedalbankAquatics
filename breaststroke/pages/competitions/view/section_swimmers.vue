<script setup lang="ts">
import { computed } from 'vue';
import { useRouter } from 'vue-router';
import { CompetitionModel } from '~/models/competitions';
import imageApi from '~/api/imageApi';

interface Athlete {
  athleteID: number;
  name: string;
  [key: string]: any;
}

const props = defineProps({
  competition: {
    type: Object as () => CompetitionModel,
    required: false,
    default: null
  },
});

const router = useRouter();

// 선수 데이터 계산
const athletes = computed(() => {
  if (!props.competition || !props.competition.extraInfo?.competitionTimes ||
    props.competition.extraInfo.competitionTimes.length === 0) {
    return [];
  }

  // 중복 athleteID 제거
  const uniqueAthletes = new Map<number, Athlete>();

  props.competition.extraInfo.competitionTimes.forEach((time: any) => {
    if (time.athleteID && time.athleteID > 0 && !uniqueAthletes.has(time.athleteID)) {
      uniqueAthletes.set(time.athleteID, {
        athleteID: time.athleteID,
        name: time.name || '이름 없음'
      });
    }
  });

  return Array.from(uniqueAthletes.values());
});

// 이미지 로드 실패 처리
const handleImageError = (event: Event): void => {
  const img = event.target as HTMLImageElement;
  const container = img.parentElement as HTMLElement;

  // 이미지를 숨기고 컨테이너에 회색 배경 추가
  img.style.display = 'none';
  container.classList.add('image-error');
};

// 선수 상세 페이지로 이동
const navigateToAthlete = (athleteID: number): void => {
  router.push(`/athlete/${athleteID}`);
};
</script>

