  <div class="section-swimmers">
    <div
      v-for="(athlete, index) in athletes"
      :key="index"
      class="section-swimmers-thumbnail"
      :title="`${athlete.name}#${athlete.athleteID}`"
      @click="navigateToAthlete(athlete.athleteID)"
    >
      <img
        v-if="imageApi.getThumbnail('athletes', athlete.athleteID)"
        :src="imageApi.getThumbnail('athletes', athlete.athleteID)"
        :alt="athlete.name"
        class="section-swimmers-thumbnail-image"
        @error="handleImageError"
      />
      <div v-else class="section-swimmers-div"></div>
    </div>
  </div>
</template>
