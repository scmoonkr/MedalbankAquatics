<script setup lang="ts">
const router = useRouter();
import { CompetitionModel } from '~/models/competitions';
import ButtonGroup from '~/components/common/TheButtonGroup.vue';
// import { SwimmingStatsProcessor } from '~/models/athleteExtraInfo';
const props = defineProps({
  competition: {
    type: CompetitionModel,
  },
});
const selectedTeam = ref('');

// 코스 옵션
const teams = computed(() => {
  if (props.competition == undefined || !props.competition.extraInfo!.teams || props.competition.extraInfo!.teams.length === 0) return [];

  const arr = [];
  const acount = props.competition.extraInfo!.teams.length < 100 ? 1 : 2;
  for (const data of props.competition.extraInfo!.teams) {
    if (props.competition.isMasters == false) { // 등록
      if ((data as any).teamID != 185 && (data as any).name.length > 0 && (data as any).timeCount >= acount) { // 개인 제외
        arr.push({ value: `${(data as any).teamID}`, label: `${(data as any).name}(${(data as any).timeCount})` });
      }

    } else { // 비등록
      if ((data as any).teamID != 185 && (data as any).name.length > 0 && (data as any).athleteCount >= acount) { // 개인 제외
        arr.push({ value: `${(data as any).teamID}`, label: `${(data as any).name}(${(data as any).athleteCount})` });
      }
    }
  }
  return arr.slice(0, 100);
});



// 선수 데이터 계산
const teams1 = computed(() => {
  if (!props.competition || !props.competition.extraInfo?.competitionTimes ||
    props.competition.extraInfo.competitionTimes.length === 0) {
    return [];
  }


  const teams = {};

  const teamMap = new Map();

  for (const time of props.competition.extraInfo.competitionTimes) {
    const key = `${time.team || '미지정'}|${time.teamID ?? 'null'}`;
    if (!teamMap.has(key)) {
      teamMap.set(key, { team: time.team || '미지정', teamID: time.teamID ?? null, count: 1 });
    } else {
      teamMap.get(key).count += 1;
    }
  }

  const arr = [];
  for (const data of teamMap.values()) {
    if ((data as any).teamID != 185) { // 개인 제외
      arr.push({ value: `${(data as any).teamID}`, label: `${(data as any).team}(${(data as any).count})` });
    }
  }
  return arr;
});



const clickButton = (teamID: string) => {
  router.push(`/team/${teamID}`);
};
</script>

