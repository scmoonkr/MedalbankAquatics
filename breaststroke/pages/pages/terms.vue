              ② 여러분은 메달뱅크 계정 웹사이트 또는 개별 서비스 내 메달뱅크 계정 설정 화면을 통하여 여러분의 메달뱅크 계정 정보를 열람하고 수정할 수 있습니다. 다만, 메달뱅크 계정 서비스의 제공 및 관리를 위해 필요한 메달뱅크 계정, 전화번호, 단말기 식별번호, 기타 본인확인정보 등 일부 정보는 수정이 불가능할 수 있으며, 수정하는 경우에는 추가적인 본인 확인 절차가 필요할 수 있습니다. 여러분이 이용 신청 시 알려주신 내용에 변동이 있을 때, 직접 수정하시거나 이메일 또는 고객센터를 통하여 회사에 알려 주시기 바랍니다.<br />
              ③ 여러분이 메달뱅크 계정 정보를 적시에 수정하지 않아 발생하는 문제에 대하여 회사는 책임을 부담하지 않습니다.
