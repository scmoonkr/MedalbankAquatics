              ② 여러분은 서비스 제공에 이용되는 공개자료 중 본인의 이름에 해당하는 정보의 블라인드(가림) 처리를 회사에 요청할 수 있습니다. 이러한 요청이 있을 경우 회사는 신속히 처리하겠습니다.
