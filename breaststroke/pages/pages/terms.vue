              ② 단체계정은 계정 정보에 등록된 담당자 1인만 이용할 수 있으며, 이를 다른 사람에게 공유하는 것은 금지됩니다.<br />
              ③ 단체계정은 개인 메달뱅크 계정으로 전환할 수 없고, 다른 개인 또는 법인 등 제3자에게 양도할 수 없습니다.<br />
              ④ 단체계정은 일부 메달뱅크 서비스의 가입 및 이용이 제한되며, 가입 및 이용이 제한되는 서비스는 정책에 따라 변경될 수 있습니다.<br />
              ⑤ 단체계정의 정보 또는 담당자 변경 요청에 대해 회사는 요청자가 해당 계정에 대한 정당한 권한이 있는지 확인하기 위하여 일정한 증빙서류를 요청할 수 있습니다.<br />
              ⑥ 단체계정은 사업자/단체에 귀속되는 것으로, 담당자는 해당 계정에 대해 권리를 주장할 수 없습니다.<br />
              ⑦ 본 조에서 정하고 있는 내용 외에 단체계정과 관련된 상세한 사항은 사업자/단체 메달뱅크 계정 운영정책에 따르며, 회사는 게시판 및 고객센터 도움말 페이지 등을 통하여 회원에게 안내하겠습니다.
