<script setup lang="ts">
import { ref, computed, onMounted, watch } from 'vue';

import TheSection from '~/components/common/TheSection.vue';
import SectionLoading from '~/components/common/TheSectionLoading.vue';
import type { JsonOptions, FilterItem } from '~/types/common';
import DisciplineFilter from '~/components/common/TheFiltersTimes.vue';

const props = defineProps({
  names: {
    type: String,
    default: '홍길동',
  },
  options: {
    type: Object,
    default: {
      discipline: '평영',
      distance: '50M',
      course: 'LCM',
    }
  },
});

// ▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓
// ▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓
// ▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓

// ref로 사용할 때의 타입
const disciplinePos = ref(0);
const filters = ref<FilterItem[]>([]);
// const filter = ref<FilterItem[]>([
//   { field: 'names', selected: '', options: [''] },
//   { field: 'discipline', selected: '전체', options: ["전체", '자유형', '배영', '평영', '접영', '개인혼영'] },
//   { field: 'distance', selected: '전체', options: ["전체", '25M', '50M', '100M', '200M', '400M', '800M', '1500M'] },
//   { field: 'course', selected: '전체', options: ["전체", 'LCM', 'SCM'] },
//   { field: 'sort', selected: '최근순', options: ['최근순', '기록순'] },
// ]);

const options = ref<JsonOptions>({
  masters: 'masters',
  gender: 'women',
  discipline: 'BR',
  distance: '50M',
  course: 'LCM',
  typeTime: 'timeResult',
});

// modelValue 변경 감지
watch(() => props.names, (rnames) => {

  if (rnames != "") {
    filters.value = [
      { field: 'names', selected: '', options: [''] },
      { field: 'discipline', selected: '전체', options: ["전체", '자유형', '배영', '평영', '접영', '개인혼영'] },
      { field: 'distance', selected: '전체', options: ["전체", '25M', '50M', '100M', '200M', '400M', '800M', '1500M'] },
      { field: 'course', selected: '전체', options: ["전체", 'LCM', 'SCM'] },
      { field: 'sort', selected: '최근순', options: ['최근순', '기록순'] },
    ];
    filters.value[0].selected = rnames;
    filters.value[0].options = [rnames];
    disciplinePos.value = 1;
  } else {
    filters.value = [
      { field: 'discipline', selected: '전체', options: ["전체", '자유형', '배영', '평영', '접영', '개인혼영'] },
      { field: 'distance', selected: '전체', options: ["전체", '25M', '50M', '100M', '200M', '400M', '800M', '1500M'] },
      { field: 'course', selected: '전체', options: ["전체", 'LCM', 'SCM'] },
      { field: 'sort', selected: '최근순', options: ['최근순', '기록순'] },
    ];
    disciplinePos.value = 0;
  }
  filters.value[disciplinePos.value].selected = getStyleKorByEng(props.options.discipline);
  filters.value[disciplinePos.value+1].selected = props.options.distance;
  filters.value[disciplinePos.value+1].selected = props.options.course;
}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가

watch(() => props.options, (options) => {

  filters.value[disciplinePos.value].selected = getStyleKorByEng(options.discipline);
  filters.value[disciplinePos.value+1].selected = options.distance;
  filters.value[disciplinePos.value+2].selected = options.course;
}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가

// filter가 변경될 때 parent로 filter 데이터를 업데이트하는 함수
const emit = defineEmits(['change-discipline']);

// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  try {
    switch (field) {
      case 'discipline':
        options.value.discipline = getDisciplineByEng(value);
        break;
      case 'gender':
        options.value.gender = getGenderByKor(value);
        break;
      case 'typeTimes':
        options.value.typeTime = getTypeTimes(value);
        break;
      case 'masters':
        options.value[field] = value === '등록' ? 'masters' : "elite";
        break;
      // case 'sort':
      //   options.value[field] = value === '최근순' ? '기록순' : "최근순";
      //   break;
      default:
        options.value[field] = value;
        break;
    } 
    emit('change-discipline', field, options.value);   
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  }
}
