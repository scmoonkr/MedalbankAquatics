import DataTable from '@/components/common/DataTable.vue';
import TheTooltipDialog from '~/components/common/TheTooltipDialog.vue';
const showTooltip = ref(false);

const router = useRouter();

// 상태 관리
const isLoading = ref(false);
const selectedItems = ref<number[]>([]);
const rowsPerPage = 1000; // UI_CONFIG.rowsPerPage;

const props = defineProps({
  times: {
    type: Array as () => TimeModel[],
    default: () => [] as TimeModel[],
  },
  page: {
    type: Number,
    default: 1,
  },
  totalPages: {
    type: Number,
    default: 1,
  },
});

//--------------------------------------------
// 계산된 속성들
//--------------------------------------------
const tableData = computed(() => {
  // return timeStore.filteredTimeList;
  return props.times.map((time: TimeModel) => {
    // checked 속성 추가
    return {
      ...time,
      checked: selectedItems.value.includes(time.timeID)
    };
  });
});

// DataTable 설정
const columns = [
  // { key: 'gender', label: '성별', sortable: false },
  { key: 'rank', label: '순위', sortable: false },
  // { key: 'ageGroup', label: 'ageGroup', sortable: false },
  { key: 'name', label: '선수', sortable: false },
  { key: 'time', label: '결과', sortable: false },
  { key: 'status', label: '비고', sortable: false },
  // { key: 'ageGroup', label: 'ageGroup', sortable: false },
  // { key: 'gender', label: 'gender', sortable: false },
  // { key: 'style', label: 'style', sortable: false },
  // { key: 'course', label: 'course', sortable: false },
  // { key: 'distance', label: 'distance', sortable: false },
  // { key: 'competitionName', label: '대회', sortable: false },
];

const currentPage = computed(() => props.page);

const clickTableCell = async (item: TimeModel, column: string) => {
  switch (column) {
    case "name":
      if (item.athleteID > 0) {
        router.push(`/athlete/${item.athleteID}`);
      } else {
        showTooltip.value = true;
      }
      break;
    case "time":
      router.push(`/time/${item.timeID}`);
      break;
  }
};
// 이미지 로드 실패 처리
const handleImageError = (event: Event): void => {
  // Event 타입은 너무 일반적이라서 target.src에 접근할 수 없습니다
  // HTMLImageElement로 타입 단언(type assertion)이 필요합니다
  (event.target as HTMLImageElement).src = '/images/not_found.jpg';
};

</script>

