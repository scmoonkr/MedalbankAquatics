});

// modelValue 변경 감지
watch(() => props.names, (rnames) => {
  filters.value[0].selected = rnames;
  filters.value[0].options = [rnames];
  // filters.value[1].selected = getStyleKorByEng(props.options.discipline);
  // filters.value[2].selected = props.options.distance;
  // filters.value[3].selected = props.options.course;
}, { deep: true, immediate: true });

watch(() => props.options, (opts) => {
  filters.value[1].selected = getDisciplineByEng(opts.discipline);
  filters.value[2].selected = opts.distance;
  filters.value[3].selected = opts.course;

  filters.value = filters.value.slice(0, 4);
  if (props.isElite) {
    filters.value.push({ field: 'masters', selected: '전체', options: ['전체', '비등록'] });
  }
}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가

// filter가 변경될 때 parent로 filter 데이터를 업데이트하는 함수
const emit = defineEmits(['change-discipline']);

// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  try {
    switch (field) {
      case 'discipline':
        options.value.discipline = getDisciplineByEng(value);
        break;
      case 'gender':
        options.value.gender = getGenderByKor(value);
        break;
      case 'typeTime':
        options.value.typeTime = getTypeTimes(value);
        break;
      // case 'masters':
      //   options.value[field] = value === '등록' ? 'masters' : "elite";
      //   break;
      default:
        options.value[field] = value;
        break;
    } 
    // console.log("++++++++++++++++++++++++++++++++", field, value, options.value);
    emit('change-discipline', field, options.value);   
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  }
}
