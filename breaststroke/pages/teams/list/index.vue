  { menu: '기록', url: '/times' },
  { menu: '선수', url: '/athletes' },
  { menu: '대회', url: '/competitions' },
];

const router = useRouter();

const authStore = useAuthStore();
const teamStore = useTeamStore();

// 상태 관리
const isLoading = ref(false);
const rowsPerPage = ref(UI_CONFIG.rowsPerPage);
const currentPage = ref(1);
///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {
  isLoading.value = true;
  try {
    isLoading.value = true;
    teamStore.filter = {
      name: '',
      course: '',
      sido: '',
      teamID: 0,
      sortField: 'points',
      sortDirection: 'desc',
    };

    teamStore.filter.sortField = TeamSortField.POINTS;
    teamStore.filter.sortDirection = SortDirection.DESC;

    currentPage.value = 1;
    await teamStore.fetchTeamList(currentPage.value, rowsPerPage.value);
    isLoading.value = false;
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
// history back시 onMount 처리
usePageNavigation(loadServerData);
///########################################################
///########################################################

// 부모 컴포넌트에 추가
const handleSortChange = async (column: string) => {
};
const handlePageChange = async (page: number) => {
  currentPage.value = page;
  await teamStore.fetchTeamList(currentPage.value, rowsPerPage.value);
};

//======================================================================
// Button
//======================================================================
const selectButtonNames = [
  { value: '', label: '모든 팀/클럽' },
  { value: 'name', label: '특정 팀/클럽' },
];
const onNameChange = async (value: string) => {
  if (value.length < 2) return;
  teamStore.filter.name = value;

  isLoading.value = true;
  currentPage.value = 1;
  await teamStore.fetchTeamList(currentPage.value, rowsPerPage.value);
  isLoading.value = false;
};

const sortsButton = [
  { value: 'points', label: '절대평가' },
  { value: 'ratio', label: '상대평가' },
];
const selectedSort = ref('points');
const onSortChange = async (value: string) => {
  teamStore.filter.sortField = value;
  teamStore.filter.sortDirection = 'desc';

  isLoading.value = true;
  currentPage.value = 1;
  await teamStore.fetchTeamList(currentPage.value, rowsPerPage.value);
  isLoading.value = false;
};

