const router = useRouter();

const props = defineProps({
  competitions: {
    type: Array as () => CompetitionModel[],
    required: false,
    default: null
  },
});


const tableData = computed(() => {
  if (props.competitions == undefined) return [];

  const competitions = props.competitions.map((competition: any) => {
    // 각 이벤트의 gold, silver, bronze 메달 수를 누적
    const totalMedals = (competition.medals?.gold || 0) +
      (competition.medals?.silver || 0) +
      (competition.medals?.bronze || 0);
    competition.isAdult = competition.isAdult ?? '성인';
    competition.isMasters = competition.isMasters ?? '마스터즈';
    // competition.fullname = getCompetition(competition.competitionID);
    return {
      ...competition,
      totalMedals
    };
  });

  // 실제 competition 객체의 구조에 따라 다음 경로를 수정해야 할 수 있습니다
  return competitions || [];
});


const columns = [
  { key: 'dateStart', label: '일자', sortable: false },
  // { key: 'isMasters', label: '카테고리', sortable: false },
  // { key: 'isAdult', label: '구분',  sortable: false },
  { key: 'fullname', label: '대회', sortable: false },
  { key: 'athleteCount', label: '참가자', sortable: false },
  { key: 'totalMedals', label: '획득메달', sortable: false },
];

// 테이블 셀 클릭 처리
const clickTableCell = (item: {}, column: string) => {

  if ((item as any).competitionID > 0) {
    router.push(`/competition/${(item as any).competitionID}`);
  }
};
</script>

