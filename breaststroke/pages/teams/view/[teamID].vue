import TheSection from '~/components/common/TheSection.vue';
import SectionLoading from '~/components/common/TheSectionLoading.vue';
import TheSpacer from '~/components/common/TheSpacer.vue';

const teamStore = useTeamStore();
const authStore = useAuthStore();
const router = useRouter();
const route = useRoute()

// 상태 관리
const isLoading = ref(false);

async function loadServerData() {

  try {
    isLoading.value = true;
    await nextTick();

    const teamIdStr = route.params.teamID;

    // 비동기 작업 완료 후 상태 확인
    await teamStore.fetchTeamById(teamIdStr);

    // sort 대회이력
    if (teamStore.currentTeam?.extraInfo?.competitions) {
      teamStore.currentTeam.extraInfo.competitions = teamStore.currentTeam.extraInfo.competitions.sort((a, b) => {
          return new Date(b.dateStart).getTime() - new Date(a.dateStart).getTime();
      });
    }

  } catch (error) {
    console.error("Error in onMounted:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
usePageNavigation(loadServerData);

const titleTeam = computed(() => {
  const name = teamStore.currentTeam?.name ?? '팀명없음';
  const id = teamStore.currentTeam?.teamID;
  if (!name && !id) return '';
  return `${name ?? ''}${id ? ` (${id})` : ''}`;
});

</script>

