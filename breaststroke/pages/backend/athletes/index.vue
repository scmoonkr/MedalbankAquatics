<script setup lang="ts">

definePageMeta({
  layout: 'backend',
});
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';
import { usePageNavigation } from '~/composables/usePageNavigation';
import type { Gender, SwimCourse, SwimStyle, Individual } from '~/types/common'

import UI_CONFIG from '~/config/ui';
import { SortDirection } from '~/types/common';
import { AthleteSortField } from '~/types/athletes';
import type { AthleteModel } from '~/models/athletes';
import { useAthleteStore } from '~/stores/athletes';
import { useAuthStore } from '~/stores/useAuthStore';

import AthletesDataTable from './athletes_table.vue';
import Header from './header.vue';
import Form from './form.vue';

const router = useRouter();

const authStore = useAuthStore();
const athleteStore = useAthleteStore();

// 상태 관리
const isLoading = ref(false);
const currentPage = ref(1);
const selectedName = ref('가');
const form = ref<Partial<AthleteModel>>({
  athleteID: 0,
  name: '',
  dob: '',
  featured: '',
  featuredBB: '',
  gender: 'men',
});
///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {
  isLoading.value = true;
  try {
    isLoading.value = true;
    athleteStore.filter = {
      name: '',
      gender: 'men',
      sortField: 'dateStart',
      sortDirection: 'desc',
    };
    athleteStore.pagination.rowsPerPage = 100; // UI_CONFIG.rowsPerPage;

    athleteStore.filter.sortField = AthleteSortField.NAME;
    athleteStore.filter.sortDirection = SortDirection.ASC;

    await athleteStore.fetchAthleteListBackend(1, athleteStore.pagination.rowsPerPage);
    isLoading.value = false;
  } catch (error) {
    // console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
// history back시 onMount 처리
usePageNavigation(loadServerData);
///########################################################
///########################################################
const clickCell = (item: AthleteModel, column: string) => {
  form.value = JSON.parse(JSON.stringify(item));
}
const onSaveForm = async (form: AthleteModel) => {
  const index = athleteStore.athleteList.findIndex(el => el.athleteID === form.athleteID);
  if (index !== -1) {
    athleteStore.athleteList[index] = form;
  } else {
    athleteStore.athleteList.splice(0, 0, form)
  }
  await athleteStore.updateAthlete(form);
}
const onDeleteForm = async (athleteID: number) => {
  const index = athleteStore.athleteList.findIndex(el => el.athleteID === athleteID);
  if (index !== -1) {
    athleteStore.athleteList.splice(index, 1);
  await athleteStore.deleteAthlete(athleteID);
  }
}
// 부모 컴포넌트에 추가
const handlePageChange = async (page: number) => {
  currentPage.value = page;
  await athleteStore.fetchAthleteListBackend(currentPage.value, athleteStore.pagination.rowsPerPage);
};
//======================================================================
// Button
//======================================================================
const onChangeFilter = async (field: string, value: string) => {
  switch (field) {
    case "name":
      athleteStore.filter.name = value;
      // if (value.length < 2) return;
      break;
    case "gender":
      athleteStore.filter.gender = value as Gender;
      break;
  }
  
  await athleteStore.fetchAthleteListBackend(currentPage.value, athleteStore.pagination.rowsPerPage);
}
const onNameSearch = async (value: string) => {
  if (value.length < 2) return;
  athleteStore.filter.name = value;

  isLoading.value = true;
  currentPage.value = 1;
  await athleteStore.fetchAthleteListBackend(currentPage.value, athleteStore.pagination.rowsPerPage);
  isLoading.value = false;
};
const onNameChange = async (value: string) => {
  selectedName.value = value;
  athleteStore.filter.name = value + "%";

  isLoading.value = true;
  currentPage.value = 1;
  await athleteStore.fetchAthleteListBackend(currentPage.value, athleteStore.pagination.rowsPerPage);
  isLoading.value = false;
};

</script>

