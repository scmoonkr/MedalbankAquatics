<script setup lang="ts">

definePageMeta({
  layout: 'backend',
});
import { ref, computed, onMounted, watch } from 'vue';
import { useRouter } from 'vue-router';
import { usePageNavigation } from '~/composables/usePageNavigation';

import UI_CONFIG from '~/config/ui';
import { SortDirection } from '~/types/common';
import { StemSortField, type Stem } from '~/types/stems';
import type { StemModel } from '~/models/stems';
import { useStemStore } from '~/stores/stems';
import { useAuthStore } from '~/stores/useAuthStore';

import StemsDataTable from './stems_table.vue';
import Header from './header.vue';
import Form from './form.vue';

const router = useRouter();

const authStore = useAuthStore();
const stemStore = useStemStore();

// 상태 관리
const isLoading = ref(false);
const currentPage = ref(1);
const selectedName = ref('가');
const form = ref<Partial<StemModel>>({
  stemID: 0,
  stem: '',
  competitions: [],
});
///########################################################
/// 컴포넌트 로딩 시 데이터 가져오기
///########################################################
async function loadServerData() {
  isLoading.value = true;
  try {
    isLoading.value = true;
    stemStore.filter = {
      stem: '',
      stemID: 0,
      sortField: 'dateStart',
      sortDirection: 'desc',
    };
    stemStore.pagination.rowsPerPage = 100; // UI_CONFIG.rowsPerPage;

    stemStore.filter.sortField = StemSortField.STEM;
    stemStore.filter.sortDirection = SortDirection.ASC;

    await stemStore.fetchStemList(1, stemStore.pagination.rowsPerPage);
    isLoading.value = false;
  } catch (error) {
    console.error("데이터 로드 오류:", error);
  } finally {
    isLoading.value = false;
  }
}

// 컴포저블 함수 사용
// history back시 onMount 처리
usePageNavigation(loadServerData);
///########################################################
///########################################################
const clickCell = (item: StemModel, column: string) => {
  form.value = JSON.parse(JSON.stringify(item));
}
const onSaveForm = async (form: StemModel) => {
  if (form.stem == "") return;

  await stemStore.updateStem(form);
  if (form.stemID > 0) {
    const index = stemStore.stemList.findIndex((el: any) => el.stemID === form.stemID);
    if (index !== -1) {
      stemStore.stemList[index] = stemStore.currentStem!;
    }
  } else {
    stemStore.stemList.splice(0, 0, stemStore.currentStem!);
  }
}
const onDeleteForm = async (stemID: number) => {
  if (stemID == 0) return;
  const index = stemStore.stemList.findIndex((el: any) => el.stemID === stemID);
  if (index !== -1) {
    stemStore.stemList.splice(index, 1);
  await stemStore.deleteStem(stemID);
  }
}
// 부모 컴포넌트에 추가
const handlePageChange = async (page: number) => {
  currentPage.value = page;
  await stemStore.fetchStemList(currentPage.value, stemStore.pagination.rowsPerPage);
};
//======================================================================
// Button
//======================================================================
const onChangeName = async (name: string) => {
  stemStore.filter.stem = name;
  if (name.length < 2) return;
  
  await stemStore.fetchStemList(currentPage.value, stemStore.pagination.rowsPerPage);
}
const searchButtonNames = [
  { value: '', label: '모든수영장' },
  { value: 'name', label: '특정수영장' },
];

</script>

