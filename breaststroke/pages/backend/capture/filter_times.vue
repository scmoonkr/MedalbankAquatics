// ▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓▓

const props = defineProps({
  options: {
    type: Object as PropType<LeaderboardFilter>,
    default: () => ({
      masters: 'masters',
      adult: '전체',
      gender: 'women',
      style: 'breaststroke',
      distance: '50M',
      course: 'LCM',
      typeTime: '대회기록',
    }),
  },
});

// ref로 사용할 때의 타입
const filters = ref<FilterItem[]>([
  { field: 'masters', selected: '비등록', options: ['등록', '비등록'] },
  { field: 'adult', selected: '전체', options: ['전체', '성인', '학생'] },
  { field: 'gender', selected: '여자', options: ['남자', '여자'] },
  { field: 'typeTime', selected: '대회기록', options: ['훈련기록', '대회기록'] },
  { field: 'cature', selected: 'stories', options: ['stories', 'posts'] },
]);

// filter가 변경될 때 parent로 filter 데이터를 업데이트하는 함수
const emit = defineEmits(['change-discipline', 'change-capture']);

// const newOptions = computed(() => {
//   const opt = props.options;
//   opt.typeTime = opt.typeTime == 'timeResult' ? "훈련기록" : "대회기록";
//   opt.gender = opt.gender == 'men' ? "남자" : "여자";
//   return opt;
// });
watch(() => props.options, async (opt) => {
  filters.value[0].selected = opt.masters || "비등록";
  filters.value[1].selected = opt.adult || "전체";
  filters.value[2].selected  = opt.gender == 'men' ? "남자" : "여자";
  filters.value[3].selected = opt.typeTime == 'timeResult' ? "훈련기록" : "대회기록";
}, { deep: true, immediate: true }); // deep과 immediate 옵션 추가


// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  try {
    switch (field) {
      case 'gender':
        props.options.gender = getGenderByKor(value);
        break;
      case 'typeTime':
        props.options.typeTime = getTypeTimes(value);
        break;
      case 'masters':
        props.options.masters = value;
        break;
      case 'adult':
        props.options.adult = value;
        break;
      case 'cature':
        emit('change-capture', value);
        return;
      default:
        props.options[field] = value;
        break;
    }
    emit('change-discipline', props.options);
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  }
}
