// 필터 변경 처리
const onFilterChange = async (field: string, value: string) => {
  const options = { ...props.options };
  try {
    switch (field) {
      case 'discipline':
        options.discipline = getDisciplineByKor(value.replace("전체", ""));
        if (options.discipline == "IM") options.distance = "200M";
        break;
      case 'gender':
        options.gender = getGenderByKor(value.replace("성별무관", ""));
        break;
      case 'typeTime':
        options.typeTime = getTypeTimes(value);
        break;
      case 'masters':
        options.masters = value;
        break;
      case 'adult':
        options.adult = value;
        break;
      default:
        options[field] = value;
        break;
    }
  } catch (error) {
    console.error("필터 적용 중 오류:", error);
  } finally {
    console.log("options=", options);
    emit('change-discipline', options);
  }
}
