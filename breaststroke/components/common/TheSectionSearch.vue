<script setup>
import { ref } from 'vue';
import TheSpacer from '~/components/common/TheSpacer.vue';

// DOM 요소에 접근하기 위한 ref 생성
const searchInput = ref(null)
const inputField = ref("")

const props = defineProps({
  setFocus: {
    type: Number,
    default: 0,
  },
  initialValue: {
    type: String,
    default: '',
  },
  placeholder: {
    type: String,
    default: '선수명 검색',
  },
});

// 버튼 클릭 시 포커스를 주는 함수
// modelValue 변경 감지
watch(() => props.setFocus, (newValue) => {
  searchQuery.value = "";
  searchInput.value.focus()
}, { deep: true });

const emit = defineEmits([
  'changed-field', 'click-search',
]);

// 페이지 변경 처리

const searchQuery = ref('');

const handleInput = () => {
  if (!searchQuery.value.trim()) return;
  emit('changed-field', searchQuery.value);
};
const clickSearch = () => {
  // if (!searchQuery.value.trim()) return;
  emit('click-search', searchQuery.value);
};
</script>


