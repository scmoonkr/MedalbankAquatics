<script setup>
import ButtonGroup from '~/components/common/TheButtonGroup.vue';

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  all: {
    type: String,
    default: '' // 전체
  },
  modelValue: {
    type: String,
    default: 'LCM'
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});
const selectedCourse = ref(props.modelValue);
const courses = [
  { value: 'LCM', label: 'LCM' },
  { value: 'SCM', label: 'SCM' },
];

// all prop에 따라 '전체' 옵션을 추가한 배열을 계산
const coursesWithAll = computed(() => {
  if (props.all) {
    // const allLabel = typeof props.all === 'string' && props.all.length > 0 
    //   ? props.all 
    //   : '전체';
    return [
      { value: '', label: props.all ?? 'all' },
      ...courses,
    ];
  }
  return courses;
});

const onCourseChange = (value) => {
  selectedCourse.value = value;
  updateValue(value);
};

const emit = defineEmits(['update:modelValue']);

const updateValue = (value) => {
  emit('update:modelValue', value);
};
</script>

