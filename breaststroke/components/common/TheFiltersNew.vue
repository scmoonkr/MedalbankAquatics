    <!-- 선택지가 1개인 경우: 자동 선택 -->
    <template v-else-if="filter.options.length === 1">
      <button
        class="button-group-filters-selected relative"
        @click="selectOption(0, filter.options[0])">
        <span v-if="filter.options[0]">{{ filter.options[0] }}</span>
      <span v-else class="select-none opacity-20">로딩중</span>
      </button>
    </template>

    <!-- 선택지가 2개 이상이지만 열려있지 않은 경우: 드롭다운 열기용 -->
    <button
      v-else-if="openIndex !== index"
      @click="toggleDropdown(index)"
      class="font-medium relative"
      :class="filter.selected ? 'button-group-filters-selected' : 'button-group-filters-unselected'">
      <span v-if="filter.selected">{{ filter.selected }}</span>
      <span v-else class="select-none opacity-20">로딩중</span>
