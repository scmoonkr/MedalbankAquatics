<script setup>
import { ref, computed, watch } from 'vue';
import ButtonGroup from '~/components/common/TheButtonGroup.vue';

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  items: {
    type: Array,
    required: true
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});

const emit = defineEmits(['update:modelValue']);

const inputValue = ref('');
const inputField = ref(false);
const displayValue = ref('');


// 입력 처리 함수
const handleInput = (e) => {
  emit('update:modelValue', e.target.value);
};
// 자식 컴포넌트에서 필터가 바뀔 때마다 수신
const onClickButton = (value) => {
  if (props.items.length > 1 && value === props.items[1].value) {
    inputField.value = true;
  }
}
</script>

