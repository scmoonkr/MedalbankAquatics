<script setup>
import ButtonGroup from '~/components/common/TheButtonGroup.vue';

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  all: {
    type: String,
    default: '' // 전체
  },
  noOfYear: {
    type: Number,
    default: 5
  },
  modelValue: {
    type: String,
    default: 'LCM'
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});
const selectedYaer = ref(props.modelValue);
const years = computed(() => {
  const buttons = props.all ? [{ value: '', label: props.all ?? "전체" }] : [];
  let noOfYear = props.noOfYear ?? 5;
  const currentYear = new Date().getFullYear();
  for (let year = currentYear; year >= currentYear - (noOfYear - 1); year--) {
    buttons.push({ value: year.toString(), label: year.toString() });
  }
  return buttons;
});

const onYaerChange = (value) => {
  selectedYaer.value = value;
  updateValue(value);
};

const emit = defineEmits(['update:modelValue']);

const updateValue = (value) => {
  emit('update:modelValue', value);
};
</script>

