<script setup>
import ButtonGroup from '~/components/common/TheButtonGroup.vue';

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  all: {
    type: String,
    default: '' // 전체
  },
  mixed: {
    type: String,
    default: '혼성'
  },
  modelValue: {
    type: String,
    default: 'LCM'
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});
const selectedGender = ref(props.modelValue);

// all prop에 따라 '전체' 옵션을 추가한 배열을 계산
const gendersWithAll = computed(() => {
  let genderArr = [
    { value: 'men', label: '남자' },
    { value: 'women', label: '여자' },
  ];
  if (props.all) {
    genderArr = [
      { value: '', label: props.all ?? 'all' },
      ...genderArr,
    ];
  }
  if (props.mixed) {
    genderArr = [
      ...genderArr,
      { value: 'mixed', label: props.mixed ?? '혼성' },
    ];
  }
  return genderArr;
});

const onGenderChange = (value) => {
  selectedGender.value = value;
  updateValue(value);
};

const emit = defineEmits(['update:modelValue']);
const updateValue = (value) => {
  emit('update:modelValue', value);
};
</script>

