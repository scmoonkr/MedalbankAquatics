<script setup>
import { ref, computed, watch } from 'vue';

const props = defineProps({
  modelValue: {
    type: String,
    default: ''
  },
  label: {
    type: String,
    default: '날짜'
  },
  id: {
    type: String,
    default: `date-input-${Math.random().toString(36).substr(2, 9)}`
  }
});

const emit = defineEmits(['update:modelValue']);

const inputValue = ref('');
const error = ref('');
const displayValue = ref('');

// 숫자만 필터링하는 함수
const filterNumbers = (value) => {
  return value.replace(/\D/g, '');
};

// 날짜가 유효한지 검사하는 함수
const isValidDate = (year, month, day) => {
  const date = new Date(year, month - 1, day);
  return date.getFullYear() === parseInt(year) &&
    date.getMonth() === month - 1 &&
    date.getDate() === parseInt(day);
};

// 입력값을 날짜 형식으로 변환하는 함수
const formatDate = (value) => {
  if (!value || value.length !== 8) {
    return '';
  }

  const year = value.substring(0, 4);
  const month = value.substring(4, 6);
  const day = value.substring(6, 8);

  if (!isValidDate(year, parseInt(month), parseInt(day))) {
    error.value = '유효하지 않은 날짜입니다.';
    return '';
  }

  error.value = '';
  return `${year}-${month}-${day}`;
};

// 입력 처리 함수
const handleInput = (e) => {
  const value = filterNumbers(e.target.value);
  inputValue.value = value;
  e.target.value = value; // 숫자만 입력되도록 설정
  emit('update:modelValue', value);
};

// 포커스를 잃었을 때 형식화 함수
const formatOnBlur = () => {
  if (inputValue.value.length > 0 && inputValue.value.length !== 8) {
    error.value = '날짜는 8자리 숫자여야 합니다 (YYYYMMDD).';
    return;
  }

  const formatted = formatDate(inputValue.value);
  if (formatted) {
    displayValue.value = formatted;
  } else if (inputValue.value) {
    displayValue.value = inputValue.value;
  }
};

// 모델 값 변경 감지
watch(() => props.modelValue, (newValue) => {
  inputValue.value = filterNumbers(newValue);
  if (inputValue.value.length === 8) {
    displayValue.value = formatDate(inputValue.value) || inputValue.value;
  } else {
    displayValue.value = inputValue.value;
  }
}, { immediate: true });
</script>

