<template>
  <div class="date-input-container">
    <label v-if="label" :for="id">{{ label }}</label>
    <input :id="id" type="text" :value="displayValue" @input="handleInput" @blur="formatOnBlur" placeholder="YYYYMMDD"
      :class="{ 'error': error }" maxlength="8" />
    <p v-if="error" class="error-message">{{ error }}</p>
  </div>
</template>


