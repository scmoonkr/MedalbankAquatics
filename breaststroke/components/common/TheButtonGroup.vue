    'selection-row overflow-x-auto scroll-hidden whitespace-nowrap snap-x snap-mandatory',
    isScrollable ? 'scroll-pl-4 scroll-pr-4 -mx-4 px-4' : ''
  ]">
    <button v-for="item in items" :key="item.value" :id="`btn-${item.value}`" :class="[
      'select-button snap-start',
      `width-${width}`,
      `height-${height}`,
      { active: modelValue === item.value }
    ]" @click="updateValue(item.value)">
      {{ item.label }}
    </button>
  </div>
  <p v-if="title && title.length > 0" class="select-hint">{{ title }}</p>
</template>


