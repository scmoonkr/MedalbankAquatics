<script setup>
import { ref, onMounted } from 'vue'

const props = defineProps({
  title: { type: String, default: '' },
  items: { type: Array, required: true },
  modelValue: { type: String, default: '' },
  all: { type: String, default: '' },
  width: {
    type: String,
    default: 'medium',
    validator: (value) =>
      ['flex', 'xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value),
  },
  height: {
    type: String,
    default: 'medium',
    validator: (value) =>
      ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge'].includes(value),
  },
})

const emit = defineEmits(['update:modelValue'])
const scrollContainer = ref(null)
const isScrollable = ref(false)

const updateValue = (value) => {
  emit('update:modelValue', value)
  const el = document.getElementById(`btn-${value}`)
  if (el) {
    el.scrollIntoView({ behavior: 'smooth', inline: 'center', block: 'nearest' })
  }
}

const checkScroll = () => {
  const el = scrollContainer.value
  if (!el) return
  isScrollable.value = el.scrollWidth > el.clientWidth
}

onMounted(() => {
  checkScroll()
  window.addEventListener('resize', checkScroll)
})
</script>

