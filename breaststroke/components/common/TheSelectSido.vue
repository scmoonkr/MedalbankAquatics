<script setup>
import ButtonGroup from '~/components/common/TheButtonGroup.vue';

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  all: {
    type: String,
    default: '' // 전체
  },
  modelValue: {
    type: String,
    default: '서울'
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});
const selectedSido = ref(props.modelValue);
const sidos = [
  { value: '서울', label: '서울' },
  { value: '경기', label: '경기' },
  { value: '인천', label: '인천' },
  { value: '강원', label: '강원' },
  { value: '충북', label: '충북' },
  { value: '충남', label: '충남' },
  { value: '대전', label: '대전' },
  { value: '경북', label: '경북' },
  { value: '대구', label: '대구' },
  { value: '울산', label: '울산' },
  { value: '부산', label: '부산' },
  { value: '경남', label: '경남' },
  { value: '전북', label: '전북' },
  { value: '전남', label: '전남' },
  { value: '광주', label: '광주' },
  { value: '제주', label: '제주' },
  { value: '세종', label: '세종' },
  { value: '해외', label: '해외' },
];

// all prop에 따라 '전체' 옵션을 추가한 배열을 계산
const sidosWithAll = computed(() => {
  if (props.all) {
    const allLabel = typeof props.all === 'string' && props.all.length > 0
      ? props.all
      : '전체';

    return [
      { value: '', label: allLabel },
      ...sidos
    ];
  }
  return sidos;
});

const onSidoChange = (value) => {
  selectedSido.value = value;
  updateValue(value);
};

const emit = defineEmits(['update:modelValue']);

const updateValue = (value) => {
  emit('update:modelValue', value);
};
</script>

