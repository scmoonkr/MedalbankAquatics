<script setup>
import ButtonGroup from '~/components/common/TheButtonGroup.vue';
import { ageGroupTable } from '~/utils/ageGroup';


const selectedAgeGroup = ref('');
const ageGroups = [
  { value: '', label: '전체' },
  ...ageGroupTable.map(age => ({ value: age.group, label: age.groupName }))
];

const props = defineProps({
  title: {
    type: String,
    default: ''
  },
  modelValue: {
    type: String,
    default: '' // 성인 전체
  },
  width: {
    type: String,
    default: 'small',
    validator: (value) => ['flex', 'xsmall', 'small', 'medium', 'large', 'xlarge', 'xxlarge', 'xxxlarge'].includes(value)
  },
  height: {
    type: String,
    default: 'small',
    validator: (value) => ['xsmall', 'small', 'medium', 'large', 'xlarge'].includes(value)
  }
});

const onAgeGroupChange = (value) => {
  selectedAgeGroup.value = value;
  updateValue(value);
};

const emit = defineEmits(['update:modelValue']);

const updateValue = (value) => {
  emit('update:modelValue', value);
};
</script>

