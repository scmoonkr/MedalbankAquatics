<script setup lang="ts">
import { computed, ref } from 'vue';
import { TimeModel } from '~/models/times';

const props = defineProps({
  leaderboard: {
    type: Object,
    default: () => { },
  },
  maxHeight: {
    type: Number,
    default: 300,
  },
  barWidth: {
    type: Number,
    default: 15, // 기본 막대 폭을 15px로 설정
  },
});
let maxTime = 0;
let minTime = 0;
// 날짜별로 정렬된 기록 계산
const sortedRecords = computed(() => {
  maxTime = Math.max(...(props.leaderboard as any).times.map((t: TimeModel) => t.timeStamp)); // 여유 추가
  minTime = Math.min(...(props.leaderboard as any).times.map((t: TimeModel) => t.timeStamp)); // 여유 추가

  if (!(props.leaderboard as any).times) return [];
  return [...(props.leaderboard as any).times].sort((a, b) => b.timeStamp - a.timeStamp);
});

// 시간에 기반한 막대 높이 계산
const calculateBarHeight = (record: TimeModel): string => {

  // 최소값은 50px, 최대값은 maxHeight가 되도록 설정
  // 높이 = ((현재값 - 최소값) / (최대값 - 최소값)) * (최대높이 - 최소높이) + 최소높이
  const minHeight = 50;
  let height;

  if (maxTime === minTime) {
    // 모든 값이 같은 경우
    height = props.maxHeight;
  } else {
    height = minHeight + ((record.timeStamp - minTime) / (maxTime - minTime)) * (props.maxHeight - minHeight);
  }

  return `${height}px`;
};
</script>

