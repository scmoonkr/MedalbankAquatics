const DAYS_KO = ['일요일','월요일','화요일','수요일','목요일','금요일','토요일']
function fmtFullDate(s: string): string {
  const [y, m, d] = s.split('.').map(Number)
  const dt = new Date(y, m - 1, d)
  return `${y}년 ${m}월 ${d}일 ${DAYS_KO[dt.getDay()]}`
}

